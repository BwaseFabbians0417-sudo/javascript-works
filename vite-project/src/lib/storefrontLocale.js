export function translate(language, key, values = {}) {
  const template = translations[language]?.[key] || translations.en[key] || key
  return template.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match))
}

export function getInitialLocalePreferences() {
  let savedCountry
  let savedLanguage
  try {
    savedCountry = window.localStorage.getItem('fengs-country-v1')
    savedLanguage = window.localStorage.getItem('fengs-language-v1')
  } catch (error) {
    console.warn('Could not read the saved FENGS region preference.', error)
  }
  const validCountry = countries.find((country) => country.code === savedCountry)
  const browserLocale = navigator.language || 'en-US'
  const browserCountryCode = browserLocale.split('-')[1]?.toUpperCase()
  const browserCountry = countries.find((country) => country.code === browserCountryCode)
  const selectedCountry = validCountry || browserCountry || countries[0]
  const browserLanguage = browserLocale.split('-')[0].toLowerCase()
  const validLanguage = languages.some((language) => language.code === savedLanguage)
    ? savedLanguage
    : languages.some((language) => language.code === browserLanguage)
      ? browserLanguage
      : selectedCountry.language
  return { countryCode: selectedCountry.code, language: validLanguage }
}

export function formatRegionalPrice(rubAmount, countryCode, language) {
  const country = countries.find((item) => item.code === countryCode) || countries[0]
  const languageLocale = { en: 'en', ru: 'ru', fr: 'fr', de: 'de' }[language] || 'en'
  const locale = country.locale.startsWith(languageLocale)
    ? country.locale
    : `${languageLocale}-${country.code}`
  try {
    return new Intl.NumberFormat(locale, {
      style: 'currency',
      currency: country.currency,
      maximumFractionDigits: ['USD', 'EUR', 'GBP', 'CAD', 'AUD'].includes(country.currency) ? 2 : 0,
    }).format(rubAmount * country.rate)
  } catch (error) {
    console.warn(`Could not format the ${country.currency} display price.`, error)
    return new Intl.NumberFormat(country.locale, { maximumFractionDigits: 0 }).format(rubAmount * country.rate)
  }
}
